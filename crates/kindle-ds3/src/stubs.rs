//! Editor stubs generated from the running game's data.
//!
//! `stubs/kindle.lua` (shipped with Kindle) describes the API. This module writes
//! `stubs/kindle-game.lua` next to it, once the player is in the world: the names the API
//! accepts, as types the Lua language server completes and checks (item, animation and
//! bonfire names; param tables and their row fields). It comes from the user's own game, so
//! it matches their language and game version, and is only rewritten when it changes.

use std::fmt::Write as _;
use std::path::Path;

use kindle_paramdef::FieldType;

use crate::text::Kind;

const FILE_NAME: &str = "kindle-game.lua";

/// A Lua string literal (names are plain text; quote and escape what needs it).
fn quoted(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c if (c as u32) < 0x20 => {}
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// `---@alias name` with one `---| "value"` line per value (empty: plain string).
fn alias(out: &mut String, name: &str, doc: &str, values: &[String]) {
    let _ = writeln!(out, "--- {doc}");
    if values.is_empty() {
        let _ = writeln!(out, "---@alias {name} string\n");
        return;
    }
    let _ = writeln!(out, "---@alias {name}");
    for v in values.iter().filter(|v| !v.trim().is_empty()) {
        let _ = writeln!(out, "---| {}", quoted(v));
    }
    out.push('\n');
}

fn field_type(f: &kindle_paramdef::Field) -> &'static str {
    match f.ty {
        FieldType::FixStr | FieldType::FixStrW => "string",
        _ if !f.is_scalar() => "integer[]",
        FieldType::Dummy8 => "integer[]",
        FieldType::F32 => "number",
        _ => "integer",
    }
}

/// The generated file's contents (sections whose data isn't available are left as plain
/// strings, so the API stubs still resolve).
fn generate() -> String {
    let mut out = String::from(
        "---@meta\n\
         -- Generated by Kindle from your game's data: names the API accepts, for autocomplete.\n\
         -- Rewritten when the game data changes; don't edit.\n\n",
    );

    let names = crate::text::item_names().ok();
    let list = |kind: Kind| names.as_ref().map(|n| n.names(kind)).unwrap_or_default();
    let (goods, weapons, armor, rings) = (list(Kind::Goods), list(Kind::Weapon), list(Kind::Armor), list(Kind::Ring));
    alias(&mut out, "kindle.goods_name", "A goods item's name (consumables, keys, materials, spells).", &goods);
    alias(&mut out, "kindle.weapon_name", "A weapon's name (shields, catalysts and ammunition included). Add \" +N\" for an upgrade level.", &weapons);
    alias(&mut out, "kindle.armor_name", "An armor piece's name.", &armor);
    alias(&mut out, "kindle.ring_name", "A ring's name.", &rings);
    out.push_str("--- Any item's name.\n---@alias kindle.item_name kindle.goods_name|kindle.weapon_name|kindle.armor_name|kindle.ring_name\n\n");

    let mut anims: Vec<String> =
        crate::game::player_chr_addr().ok().and_then(|p| crate::anim::names(p).ok()).map(|v| v.into_iter().map(|(_, n)| n).collect()).unwrap_or_default();
    anims.sort_by_key(|n| n.to_lowercase());
    anims.dedup();
    alias(&mut out, "kindle.animation_name", "An animation event the player's behaviour accepts (e.g. \"W_Rolling\").", &anims);

    let mut bonfires: Vec<String> = crate::bonfire::all().map(|all| all.into_iter().filter_map(|b| b.name).collect()).unwrap_or_default();
    bonfires.sort();
    bonfires.dedup();
    alias(&mut out, "kindle.bonfire_name", "A bonfire's name.", &bonfires);
    out.push_str("--- Each bonfire's lit flag, by name (kindle.flags.bonfire).\n---@class kindle.bonfire_flags\n");
    for (name, flag) in crate::lua_values::bonfire_flags() {
        let _ = writeln!(out, "---@field {name} integer {flag}");
    }
    out.push('\n');

    let registry = crate::params::registry().ok();
    let tables: Vec<&crate::params::Table> = registry.as_ref().map(|r| r.tables().collect()).unwrap_or_default();
    let mut table_names: Vec<String> = tables.iter().map(|t| t.name.clone()).collect();
    table_names.sort();
    alias(&mut out, "kindle.param_table", "A param table's name.", &table_names);
    for t in &tables {
        let _ = writeln!(out, "--- A row of {} ({}).", t.name, t.def.param_type);
        let _ = writeln!(out, "---@class {} : kindle.param_row", t.name);
        for f in &t.def.fields {
            if f.name.is_empty() || f.name.starts_with("pad") || f.name.starts_with("dummy") {
                continue;
            }
            let _ = writeln!(out, "---@field {} {}", f.name, field_type(f));
        }
        out.push('\n');
    }
    out
}

/// Writes the generated stubs into `<kindle>/stubs` if they changed. Returns whether the
/// item names were available (the player must be in the world for everything to be).
pub fn write(kindle_dir: &Path) -> Result<bool, String> {
    let dir = kindle_dir.join("stubs");
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let path = dir.join(FILE_NAME);
    let contents = generate();
    let complete = crate::text::item_names().is_ok() && crate::game::player_chr_addr().is_ok();
    if std::fs::read_to_string(&path).ok().as_deref() != Some(contents.as_str()) {
        std::fs::write(&path, &contents).map_err(|e| format!("{}: {e}", path.display()))?;
        crate::info!("editor stubs: wrote {}", path.display());
    }
    Ok(complete)
}
